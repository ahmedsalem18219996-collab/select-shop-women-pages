const MAX_GALLERY = 5;

export const esc = (s) => String(s).replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const egp = (minor) => new Intl.NumberFormat("ar-EG").format(minor / 100);

