export function photos(product) {
  const media = (product.media || []).filter(m => MEDIA.test(m.url));
  media.sort((a, b) => (b.isPrimary === true) - (a.isPrimary === true) || a.position - b.position);
  return media.slice(0, 1 + MAX_GALLERY);
}

