import { test, expect } from '@playwright/test';
const LP = '/lp/ss-1011/?utm_source=facebook&utm_campaign=ss1011_focused';
test('original pullover only: direct order, correct quantity and no cart button', async ({ page, request }) => {
  const external=[]; page.on('request',r=>{if(new URL(r.url()).hostname!=='127.0.0.1')external.push(r.url());});
  await page.goto(LP);
  await expect(page.locator('#lpPrice')).toHaveText('٥٥٠');
  await expect(page.locator('#lpAddCart')).toBeHidden();
  await expect(page.locator('#lpColors .chip')).toHaveCount(0);
  await expect(page.locator('#lpHero img')).toHaveAttribute('src', /SS-1011/);
  await page.locator('#lpQtyUp').click();
  await page.locator('[name=name]').fill('اختبار معزول');
  await page.locator('[name=phone]').fill('01012345678');
  await page.locator('[name=region]').selectOption('cairo');
  await page.locator('[name=address]').fill('عنوان اختبار محلي فقط');
  await expect(page.locator('#lpTotal')).toHaveText('١٬١٧٠ ج');
  await page.screenshot({path:'preview-output/sweater-'+test.info().project.name+'.png',fullPage:true});
  const before=(await (await request.get('/__mock/log')).json()).orders.length;
  await page.locator('#lpOrder').click();
  await expect(page.locator('#lpDone')).toBeVisible();
  const after=(await (await request.get('/__mock/log')).json()).orders;
  expect(after.length).toBe(before+1);
  expect(after.at(-1).lines.map(l=>[l.publicCode,l.quantity])).toEqual([['SS-1011',2]]);
  expect(external).toEqual([]);
});
